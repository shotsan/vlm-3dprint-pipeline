"""Visual diff and printability critique agent for closed-loop self-refinement."""

import json
import re
from pathlib import Path
from typing import List, Optional, Tuple

from vlm_pipeline.models.spec import CriticFeedback, PrintabilityAuditResult
from vlm_pipeline.vision.vlm_client import VLMClient
from vlm_pipeline.config import config


CRITIC_SYSTEM_PROMPT = """You are an automated Quality Assurance Engineer and CAD Auditor.
You are comparing a reference photograph/drawing against synthetic renders of a 3D model generated by Blender.

Your objective:
1. Identify any geometric discrepancies (missing holes, incorrect bevel/fillet radii, mismatched aspect ratios, inverted features).
2. Review the physical printability audit results (manifoldness, overhangs, minimum wall thickness).
3. If discrepancies exist or printability fails, emit surgical Python modifications to fix the `bpy` script.
4. If the model visually matches and printability checks pass, set `approved_for_slicing` to true.

Output format: Return ONLY a valid JSON object matching the requested schema. No markdown outside the JSON.
"""

CRITIC_USER_TEMPLATE = """Evaluate the generated 3D model against the target reference image.

[Input Images Provided]:
1. Original Reference Image
2. Synthetic Renders from Blender (Orthographic Top, Front, Side, and Isometric wireframe)

[Printability Audit Telemetry]:
- Watertight / Manifold: {is_watertight}
- Non-Manifold Edges: {non_manifold_edges}
- Intersecting Faces: {intersecting_faces}
- Overhang Faces > 45°: {overhang_faces}
- Thin Wall Faces (< 1.2mm): {thin_walls}
- Volume: {volume} cm³

[Current Blender Code]:
```python
{current_code}
```

Critic Instructions:
- Compare the synthetic render directly to the original photo.
- Check if all key functional features exist in the right proportions.
- If changes are needed, provide the updated, corrected, and complete `bpy_code` to address both visual mismatch and any printability failures.

JSON Output Schema:
{{
  "feedback": {{
    "iteration": {iteration},
    "alignment_score": 0.92,
    "discrepancies": ["Base plate fillet radius too small (should be 5mm not 2mm)", "Missing counterbore on screw holes"],
    "code_modifications": ["Updated fillet edge filter to radius 5.0", "Added cylinder subtraction for counterbore"],
    "approved_for_slicing": false
  }},
  "updated_bpy_code": "import bpy\\n# complete updated script..."
}}
"""


class VisualCritic:
    """Evaluates synthetic renders against reference photos in a closed-loop."""

    def __init__(self, vlm_client: Optional[VLMClient] = None):
        self.client = vlm_client or VLMClient()

    def evaluate(
        self,
        reference_image_path: Path,
        render_image_paths: List[Path],
        audit_result: PrintabilityAuditResult,
        current_code: str,
        iteration: int
    ) -> Tuple[CriticFeedback, str]:
        """Perform visual diff and printability critique."""
        prompt = CRITIC_USER_TEMPLATE.format(
            is_watertight=audit_result.is_watertight,
            non_manifold_edges=audit_result.non_manifold_edges,
            intersecting_faces=audit_result.intersecting_faces,
            overhang_faces=audit_result.overhang_faces_exceeding_threshold,
            thin_walls=audit_result.thin_wall_faces,
            volume=round(audit_result.volume_cm3, 2),
            current_code=current_code,
            iteration=iteration
        )

        all_images = [reference_image_path] + render_image_paths

        raw_response = self.client.complete_multimodal(
            prompt=prompt,
            image_paths=all_images,
            system_prompt=CRITIC_SYSTEM_PROMPT,
            temperature=0.1
        )

        return self._parse_critic_response(raw_response, current_code)

    def _parse_critic_response(self, text: str, fallback_code: str) -> Tuple[CriticFeedback, str]:
        cleaned = text.strip()
        if "```json" in cleaned:
            cleaned = cleaned.split("```json")[1].split("```")[0].strip()
        elif "```" in cleaned:
            cleaned = cleaned.split("```")[1].split("```")[0].strip()

        try:
            data = json.loads(cleaned)
        except json.JSONDecodeError:
            match = re.search(r"\{[\s\S]*\}", cleaned)
            if match:
                data = json.loads(match.group(0))
            else:
                # If parsing fails, fall back gracefully
                feedback = CriticFeedback(
                    iteration=0,
                    alignment_score=0.5,
                    discrepancies=["Failed to parse structured critic output"],
                    approved_for_slicing=False
                )
                return feedback, fallback_code

        feedback = CriticFeedback(**data["feedback"])
        updated_code = data.get("updated_bpy_code") or fallback_code
        return feedback, updated_code
